@router.put("/bills/{bill_id}", response_model=BillResponse)
def update_bill_full(bill_id: int, updated_bill: BillUpdate, session: Session = Depends(get_session)):
    db_bill = session.get(Bill, bill_id)
    if not db_bill:
        raise HTTPException(status_code=404, detail="Bill not found")

    # Overwrite all data fields
    # Extract data safely, bypassing strict model validation rules during dump
    bill_data = updated_bill.model_dump(mode="python", exclude={"id"})
    db_bill.sqlmodel_update(bill_data)
    db_bill.reviewed_at = datetime.utcnow()

    session.add(db_bill)
    session.commit()
    session.refresh(db_bill)
    return db_bill
