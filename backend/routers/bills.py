from datetime import date, datetime, UTC
from typing import List, Optional

from fastapi import APIRouter, File, HTTPException, UploadFile, Depends, Query
from sqlmodel import Session, select

from ..database import get_session
from ..models import Bill, BillCategory, BillResponse, BillStatus, BillUpdate

from ..services.ai_analyzer import extract_bill_data_with_groq

router = APIRouter(prefix="/bills", tags=["Bills"])

@router.post(
    "/upload",
    response_model=BillResponse,
    summary="Upload a receipt image, extract data via Groq, store as pending",
    tags=["Bills"],
)
async def upload_bill(
    file: UploadFile = File(...),
    session: Session = Depends(get_session),
):
    """
    1️⃣ Read the uploaded image (in‑memory – you may add size limits later).  
    2️⃣ Call `_extract_with_groq` to get `bill_date`, `vendor_name` and `total_amount`.  
    3️⃣ Insert a new `Bill` row with `status = pending`.  
    4️⃣ Return the created record (including its autogenerated `id`).
    """
    # ----- 1. read file -------------------------------------------------
    image_bytes = await file.read()
    if not image_bytes:
        raise HTTPException(status_code=400, detail="Empty file uploaded")

    # ----- 2. OCR via Groq -----------------------------------------------
    extracted = await extract_bill_data_with_groq(image_bytes)

    # Convert strings to proper Python types
    try:
        billdate = date.fromisoformat(extracted["bill_date"])
        vendor = str(extracted["vendor_name"])
        amount = float(extracted["total_amount"])
    except Exception as exc:
        raise HTTPException(
            status_code=422,
            detail=f"Invalid data returned from Groq: {exc}",
        )

    # ----- 3. Persist the pending bill ------------------------------------
    new_bill = Bill(
        bill_date=billdate,
        vendor_name=vendor,
        total_amount=amount,
        category=BillCategory.miscellaneous,
        status=BillStatus.pending,
    )
    session.add(new_bill)
    session.commit()
    session.refresh(new_bill)

    # ----- 4. Return the created record ----------------------------------
    return new_bill


@router.get("/review", response_model=List[Bill])
def review_bills(
    *,
    session: Session = Depends(get_session),
    skip: int = Query(0, ge=0),
    limit: int = Query(50, le=200),
    status: Optional[BillStatus] = None,
    vendor_name: Optional[str] = None,
    category: Optional[BillCategory] = None,
):
    """
    Return a paginated list of bills.
    Optional filters: status, vendor_name.
    """
    stmt = (
        select(Bill)
        .offset(skip)
        .limit(limit)
    )
    if status:
        stmt = stmt.where(Bill.status == status)
    if status:
        stmt = stmt.where(Bill.category == category)
    if vendor_name:
        stmt = stmt.where(Bill.vendor_name.ilike(f"%{vendor_name}%"))

    results = session.exec(stmt).all()

    return results


@router.put("/{bill_id}", response_model=BillResponse)
def update_bill_full(bill_id: int, updated_bill: BillUpdate, session: Session = Depends(get_session)):
    db_bill = session.get(Bill, bill_id)
    if not db_bill:
        raise HTTPException(status_code=404, detail="Bill not found")

    # Overwrite all data fields
    # Extract data safely, bypassing strict model validation rules during dump
    bill_data = updated_bill.model_dump(mode="python", exclude={"id"})
    db_bill.sqlmodel_update(bill_data)
    db_bill.reviewed_at = datetime.now(UTC)

    session.add(db_bill)
    session.commit()
    session.refresh(db_bill)
    return db_bill
